/* ------------------------------------------------------------------ *
 * dashboard aggregates (counts of entries — never measures)          *
 * ------------------------------------------------------------------ */

function dashboard() {
  const live = ENTRIES.filter((e) => e.published).length;
  const draft = ENTRIES.length - live;

  const weeks = new Map();
  for (const e of ENTRIES) {
    const d = new Date(e.modified);
    const day = d.getUTCDate();
    const wk = `Jul ${String(1 + Math.floor((day - 1) / 7) * 7).padStart(2, '0')}`;
    weeks.set(wk, (weeks.get(wk) || 0) + 1);
  }
  const velocity = [...weeks.entries()].sort().map(([week, count]) => ({ week, count }));

  const days = new Map();
  for (const e of ENTRIES) days.set(e.modified.slice(0, 10), (days.get(e.modified.slice(0, 10)) || 0) + 1);
  const calendar = [...days.entries()].sort().map(([date, count]) => ({ date, count }));

  // Recently edited: titles only — no reference, no field values.
  const recent = [...ENTRIES].sort((a, b) => (a.modified < b.modified ? 1 : -1))
    .slice(0, 8).map((e) => ({ title: e.title }));

  return {
    collections: [
      { name: 'Build Reports', entries: ENTRIES.length, model: 'build_report' },
      { name: 'Changelog', entries: 26, model: 'changelog_note' },
      { name: 'Runbooks', entries: 14, model: 'runbook' },
      { name: 'Site copy', entries: 9, model: 'fragment' },
    ],
    counts: { live, draft, scheduled: 0, total: ENTRIES.length },
    velocity,
    calendar,
    recent,
    checklist: CHECKLIST,
    plugins: PLUGINS,
    unread: INBOX.filter((t) => t.unread).length,
  };
}

