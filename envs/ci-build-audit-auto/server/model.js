function seoPanel(e) {
  const rnd = mulberry32(101 + e.record.build_id);
  const score = 58 + Math.floor(rnd() * 40);
  const pool = [
    ['Meta description', 'Meta description is 41 characters; aim for 120–158.'],
    ['Heading order', 'One H2 follows another without intervening prose.'],
    ['Internal links', 'No internal link to the collection index.'],
    ['Alt text', 'Hero image has no alternative text.'],
    ['Canonical', 'Canonical URL inherits the collection default.'],
    ['Reading time', 'Body is shorter than the 300-word site minimum.'],
  ];
  const n = 2 + Math.floor(rnd() * 3);
  return { score, suggestions: pool.slice(0, n).map(([t, d]) => ({ title: t, detail: d })) };
}

