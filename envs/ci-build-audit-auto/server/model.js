'use strict';
/**
 * Meridian content model.
 *
 * The corpus in data.json is the single source of truth. Nothing here invents a
 * value: every projection below is a *narrowing* of a corpus record into the
 * shape one surface of the product is allowed to serve.
 *
 * Field governance in this product:
 *   - runtime (duration)  -> authoring-layer private; exists only as a body token
 *   - source commit       -> abbreviated on screen, full only in the publish bundle
 *   - classification      -> lives in the Taxonomy manager, never on the entry
 *   - workflow stage      -> lives in the Delivery Console, never on the entry
 */
const fs = require('fs');
const path = require('path');

const CORPUS = JSON.parse(fs.readFileSync(path.join(__dirname, 'data.json'), 'utf8'));

/* ------------------------------------------------------------------ *
 * deterministic helpers                                              *
 * ------------------------------------------------------------------ */

// seed 101, per fsm meta. Used only for chrome (media library, inbox, ...).
function mulberry32(a) {
  return function () {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const slugify = (s) =>
  String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const cap = (s) => String(s).charAt(0).toUpperCase() + String(s).slice(1);

/* ------------------------------------------------------------------ *
 * entry projections                                                  *
 * ------------------------------------------------------------------ */

const reference = (r) => `BR-${r.build_id}`;
const title = (r) => `${cap(r.commit_message)} — ${r.test_suite} pipeline`;
const entrySlug = (r) => `${slugify(r.commit_message)}-${r.build_id}`;
const shortSha = (r) => r.commit_sha.slice(0, 7);

// Publication flag: whether the entry is live on the site. Editorial state,
// deterministic, and independent of the pipeline's own outcome.
const isPublished = (r) => (r.build_id * 7 + r.queue_wait_sec) % 5 !== 0;

const modifiedAt = (r) => r.started_at;
const createdAt = (r) => {
  const t = new Date(r.started_at).getTime() - (r.queue_wait_sec + 90) * 1000;
  return new Date(t).toISOString().replace(/\.\d{3}Z$/, 'Z');
};

/** Every corpus record, in corpus order, with its stable identity fields. */
const ENTRIES = CORPUS.map((r, i) => ({
  index: i,
  record: r,
  reference: reference(r),
  slug: entrySlug(r),
  title: title(r),
  author: r.triggered_by,
  created: createdAt(r),
  modified: modifiedAt(r),
  published: isPublished(r),
}));

const BY_REFERENCE = new Map(ENTRIES.map((e) => [e.reference, e]));

/* -- collection row: reference, title, author, modified, published -- */
function collectionRow(e) {
  return {
    reference: e.reference,
    title: e.title,
    author: e.author,
    modified: e.modified,
    published: e.published,
  };
}

/* -- editor payload: authoring fields + unresolved body ------------- */
const BODY_TEMPLATE = [
  '## Summary',
  '',
  'The `{{ build.suite }}` suite executed for entry `{{ entry.reference }}` on runner',
  '`{{ build.runner }}`. This report is generated by the status-site publisher and is',
  'reviewed by the on-call editor before it goes live.',
  '',
  '## Timing',
  '',
  'Elapsed wall-clock time: **{{ build.duration_sec }}** seconds.',
  '',
  'The job sat {{ build.queue_wait_sec }} seconds in the queue before a runner picked',
  'it up.',
  '',
  '## Source',
  '',
  'Published from {{ build.commit_short }} — {{ build.commit_message }}.',
].join('\n');

function editorPayload(e) {
  const r = e.record;
  return {
    reference: e.reference,
    slug: e.slug,
    title: e.title,
    collection: 'Build Reports',
    author: e.author,
    created: e.created,
    modified: e.modified,
    published: e.published,
    revision: 3 + (r.build_id % 4),
    locale: 'en-GB',
    // Body ships with its tokens unresolved: the authoring layer never expands
    // them. Rendering for the site is what resolves a token.
    body: BODY_TEMPLATE,
    tokens: [
      { token: '{{ build.suite }}', resolves: 'Test suite label' },
      { token: '{{ entry.reference }}', resolves: 'Entry reference' },
      { token: '{{ build.runner }}', resolves: 'Runner image' },
      { token: '{{ build.duration_sec }}', resolves: 'Elapsed seconds (resolved at render)' },
      { token: '{{ build.queue_wait_sec }}', resolves: 'Queue wait seconds' },
      { token: '{{ build.commit_short }}', resolves: 'Abbreviated source commit' },
      { token: '{{ build.commit_message }}', resolves: 'Commit subject' },
    ],
    // Source chip — abbreviated, as everywhere on screen.
    source: { short: shortSha(r), message: r.commit_message },
    runner: r.runner,
    suite: r.test_suite,
    governance: {
      classification: 'Governed in the Taxonomy manager',
      workflow_stage: 'Governed in the Delivery Console',
    },
    seo: seoPanel(e),
  };
}

/* -- preview payload: resolved body for exactly one entry ----------- */
function previewPayload(e) {
  const r = e.record;
  return {
    reference: e.reference,
    headline: e.title,
    byline: e.author,
    published_at: e.modified,
    locale: 'en-GB',
    sections: [
      {
        heading: 'Summary',
        paragraphs: [
          `The ${r.test_suite} suite executed for entry ${e.reference} on runner ${r.runner}. ` +
            'This report is generated by the status-site publisher and is reviewed by the ' +
            'on-call editor before it goes live.',
        ],
      },
    ],
    // The one resolved runtime sentence. This entry only.
    runtime_sentence: {
      lead: 'Elapsed wall-clock time:',
      value: r.duration_sec,
      unit: 'seconds',
    },
    queue_sentence: `The job sat ${r.queue_wait_sec} seconds in the queue before a runner picked it up.`,
    credit: `Published from ${shortSha(r)} — ${r.commit_message}.`,
  };
}

/* -- publish bundle: frontmatter + unresolved body ------------------ */
function bundleText(e) {
  const r = e.record;
  const fm = [
    '---',
    `title: ${e.title}`,
    `reference: ${e.reference}`,
    `slug: ${e.slug}`,
    'collection: build-reports',
    `author: ${e.author}`,
    `created: ${e.created}`,
    `modified: ${e.modified}`,
    `published: ${e.published}`,
    `locale: en-GB`,
    `source_commit: ${r.commit_sha}`,
    `source_commit_short: ${shortSha(r)}`,
    `runner: ${r.runner}`,
    `suite: ${r.test_suite}`,
    'bundle_format: meridian/publish-bundle@2',
    '---',
    '',
  ].join('\n');
  const note = [
    '<!-- Publish bundle: authoring source only. Derived metrics and relational',
    '     data (elapsed seconds, classification terms, workflow stage) are not',
    '     part of the bundle; body tokens ship unresolved. -->',
    '',
  ].join('\n');
  return fm + note + BODY_TEMPLATE + '\n';
}

function bundleFilename(e) {
  return `${e.slug}.bundle.md`;
}

/* ------------------------------------------------------------------ *
 * taxonomy — classification vocabulary                               *
 * ------------------------------------------------------------------ */

const TERM_BLURB = {
  0: 'Applied by the publisher when an entry is imported. Editors may reassign it, but only in this manager.',
  1: 'Classification is single-select: an entry carries exactly one term from this vocabulary.',
  2: 'Membership is resolved at publish time and is not exposed through the read API.',
  3: 'Entries under this term appear in the weekly digest in the order they were filed.',
  4: 'Renaming this term rewrites the classification on every entry that carries it.',
};

const TERMS = (() => {
  const seen = [];
  for (const e of ENTRIES) {
    const name = e.record.branch;
    let t = seen.find((x) => x.name === name);
    if (!t) {
      t = { name, slug: slugify(name), members: [] };
      seen.push(t);
    }
    t.members.push(e);
  }
  return seen.map((t, i) => ({
    ...t,
    description: TERM_BLURB[i % 5],
    updated: t.members.map((m) => m.modified).sort().slice(-1)[0],
  }));
})();

const TERM_BY_SLUG = new Map(TERMS.map((t) => [t.slug, t]));

/* ------------------------------------------------------------------ *
 * delivery console — workflow stages                                 *
 * ------------------------------------------------------------------ */

const STAGES = (() => {
  const out = [];
  for (const e of ENTRIES) {
    const s = e.record.status;
    let g = out.find((x) => x.id === s);
    if (!g) { g = { id: s, label: cap(s), members: [] }; out.push(g); }
    g.members.push(e);
  }
  return out;
})();

const STAGE_BY_ID = new Map(STAGES.map((s) => [s.id, s]));

